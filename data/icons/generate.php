function buildIconEntry($name, $extraTerms, $category) {
    $terms = str_replace('-', ' ', $name);
    if (isset($extraTerms[$name])) {
        $terms .= ' ' . $extraTerms[$name];
    }
    return [
        'name' => $name,
        'searchTerms' => $terms,
        'category' => $category,
    ];
}

